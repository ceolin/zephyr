"""
Generate the extra linker script used to link a native simulator executable
with a Zephyr image built with CONFIG_USERSPACE.

The POSIX architecture protects the RAM of the image with the host page
permissions while user mode threads run. The image is partially linked, and
its sections are then linked together with the native simulator runner ones,
which by default mixes the RAM of both. This script gathers the RAM of the
image in page aligned output sections, delimited by _image_ram_start and
_image_ram_end, and leaves out the RAM of the runner.

The RAM of the image is every section of the partially linked image from
app_smem (the first RAM section of include/zephyr/arch/posix/linker.ld) on.
These sections are kept in their original order, as the image linker script
defines symbols relative to them. They are all kept, as the image linker
script could not mark them to be kept in this final link.

The writable sections placed before app_smem by the image linker script
(writable data that other targets would place in ROM, like the ztest test
descriptors) and the native simulator interface data stay accessible.

The kernel object lookup table is generated from a provisional executable
linked with this script and then linked in the final one, so the sections
holding it, or reserving room for it, are kept and aligned explicitly for both
executables to have the same layout.
"""

import argparse
import sys

from elftools.elf.constants import SH_FLAGS
from elftools.elf.elffile import ELFFile

FIRST_RAM_SECTION = "app_smem"
BSS_SECTIONS = ("bss", "noinit", "priv_stacks_noinit")
KOBJECT_DATA_SECTION = "kobject_data"
KOBJECT_ALIGN = 64
IMAGE = "*.loc_cpusw.o"


def image_sections(elf_path):
    """Return the names of the RAM sections, and of the other writable ones"""
    ram = []
    other_writable = []
    in_ram = False

    with open(elf_path, "rb") as f:
        elf = ELFFile(f)
        for section in elf.iter_sections():
            name = section.name
            flags = section["sh_flags"]

            if name == FIRST_RAM_SECTION:
                in_ram = True
            if name.startswith(".") or not flags & (SH_FLAGS.SHF_ALLOC | SH_FLAGS.SHF_WRITE):
                continue
            if in_ram:
                ram.append(name)
            elif flags & SH_FLAGS.SHF_WRITE:
                other_writable.append(name)

    if not in_ram:
        sys.exit(f"{elf_path}: no {FIRST_RAM_SECTION} section")

    return ram, other_writable


def keep(name):
    return f"\t\tKEEP({IMAGE}({name}))\n"


def generate(ram, other_writable, page_size):
    out = "/* Generated by gen_native_userspace_ld.py, do not edit */\n\n"

    out += "SECTIONS\n{\n"
    out += "\tzephyr_writable :\n\t{\n"
    for name in other_writable:
        out += keep(name)
    out += f"\t\tKEEP({IMAGE}(.native_sim_if.data))\n"
    out += "\t}\n} INSERT AFTER .data;\n\n"

    out += "SECTIONS\n{\n"
    out += f"\tzephyr_ram : ALIGN({page_size})\n\t{{\n"
    out += "\t\t_image_ram_start = .;\n"
    for name in ram:
        if name in BSS_SECTIONS:
            continue
        if name == KOBJECT_DATA_SECTION:
            out += f"\t\t. = ALIGN({KOBJECT_ALIGN});\n"
        out += keep(name)
        if name == FIRST_RAM_SECTION:
            out += f"\t\t. = ALIGN({page_size});\n"
    out += "\t}\n\n"
    out += f"\tzephyr_ram_bss (NOLOAD) : ALIGN({page_size})\n\t{{\n"
    for name in ram:
        if name in BSS_SECTIONS:
            out += keep(name)
    out += f"\t\t{IMAGE}(COMMON)\n"
    out += f"\t\t. = ALIGN({page_size});\n"
    out += "\t\t_image_ram_end = .;\n"
    out += "\t}\n} INSERT BEFORE .bss;\n\n"

    out += "SECTIONS\n{\n"
    out += f"\tzephyr_rodata : ALIGN({KOBJECT_ALIGN})\n\t{{\n"
    out += keep("rodata")
    out += "\t}\n} INSERT AFTER .rodata;\n\n"

    # The read-only data of the image is in the host .rodata, followed by its
    # own rodata section
    out += "__rodata_region_start = ADDR(.rodata);\n"
    out += "__rodata_region_end = ADDR(zephyr_rodata) + SIZEOF(zephyr_rodata);\n\n"

    out += "SECTIONS\n{\n"
    out += "\tzephyr_kobject_text : ALIGN(16)\n\t{\n"
    out += keep("kobject_text")
    out += "\t}\n} INSERT AFTER .text;\n"

    return out


def parse_args():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
        allow_abbrev=False,
    )
    parser.add_argument("-e", "--elf", required=True, help="Partially linked image")
    parser.add_argument("-o", "--output", required=True, help="Output linker script")
    parser.add_argument("-p", "--page-size", required=True, type=int, help="Host page size")
    return parser.parse_args()


def main():
    args = parse_args()

    ram, other_writable = image_sections(args.elf)
    script = generate(ram, other_writable, args.page_size)

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(script)


if __name__ == "__main__":
    main()
